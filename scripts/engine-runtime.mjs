// Builds src/engine/runtimeSource.generated.ts from src/engine/core.ts.
// core.ts is written in a restricted TS subset (only `: any` annotations, top-level declarations)
// so it can be embedded as plain JS / TS text into generated HTML, React and Web Component exports.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

export const stripExports = (src) => src.replace(/^export\s+/gm, "");

export const stripTypes = (src) =>
  stripExports(src)
    .replace(/\s+as\s+any\b/g, "")
    .replace(/:\s*any(\[\])?(?![A-Za-z0-9_$])/g, "");

export function buildRuntimeModule(coreSource) {
  const ts = stripExports(coreSource);
  const js = stripTypes(coreSource);
  return (
    "// AUTO-GENERATED by scripts/engine-runtime.mjs from src/engine/core.ts. Do not edit; run `npm run gen:runtime`.\n" +
    `export const FORMIFY_RUNTIME_TS = ${JSON.stringify(ts)};\n` +
    `export const FORMIFY_RUNTIME_JS = ${JSON.stringify(js)};\n`
  );
}

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const corePath = join(root, "src/engine/core.ts");
const outPath = join(root, "src/engine/runtimeSource.generated.ts");

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(outPath, buildRuntimeModule(readFileSync(corePath, "utf8")));
  console.log("Wrote", outPath);
}
